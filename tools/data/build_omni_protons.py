"""Rebuild data/omni-protons.js: OMNI2 hourly integral proton flux above 10 MeV, 2017-09-04 to 2017-09-16.

Raw input (not committed): https://spdf.gsfc.nasa.gov/pub/data/omni/low_res_omni/omni2_2017.dat
(NASA GSFC SPDF, OMNI2 low-resolution hourly data). Format:
https://spdf.gsfc.nasa.gov/pub/data/omni/low_res_omni/omni2.text  (word 1 year, 2 day of year,
3 hour, 46 proton flux > 10 MeV in 1/(cm^2 s sr); 99999.99 is a fill value). Per the OMNI
documentation the flux comes from GOES at geostationary orbit.

Usage: python3 -I tools/data/build_omni_protons.py RAW_DAT data/omni-protons.js

Fill values are written as null, never interpolated.

Written with an SI tool (Claude) and reviewed by the team.
"""
import datetime as dt
import json
import sys

start, end = dt.datetime(2017, 9, 4), dt.datetime(2017, 9, 17)
rows = []
for line in open(sys.argv[1]):
    p = line.split()
    t = dt.datetime(int(p[0]), 1, 1) + dt.timedelta(days=int(p[1]) - 1, hours=int(p[2]))
    if start <= t < end:
        x = float(p[45])
        rows.append([t.strftime("%Y-%m-%dT%H:00Z"), None if x >= 99999.0 else x])
data = {
    "name": "OMNI2 hourly proton flux above 10 MeV",
    "source": "NASA Goddard Space Flight Center, Space Physics Data Facility (SPDF), OMNI2 hourly dataset (proton flux from GOES).",
    "url": "https://spdf.gsfc.nasa.gov/pub/data/omni/low_res_omni/omni2_2017.dat",
    "retrieved": "2026-11-14",
    "units": "gt10MeV_pfu: integral proton flux above 10 MeV, protons per (cm2 s sr) (pfu); hour: UTC start of the hour.",
    "processing": "Word 46 of omni2_2017.dat for each hour from 2017-09-04T00Z to 2017-09-16T23Z, copied as given; fill values (>= 99999) become null. Rebuild: python3 -I tools/data/build_omni_protons.py omni2_2017.dat data/omni-protons.js",
    "terms": "NASA SPDF data are public; acknowledge \"OMNI data from GSFC/SPDF OMNIWeb\".",
    "columns": ["hour", "gt10MeV_pfu"],
    "rows": rows,
}
HEAD = """/*
 * OMNI2 hourly proton flux above 10 MeV, 2017-09-04 to 2017-09-16 (NASA
 * GSFC SPDF). Real measurements; see data/README.md. Generated by
 * tools/data/build_omni_protons.py; do not edit by hand.
 *
 * Written with an SI tool (Claude) and reviewed by the team.
 */
"""
body = json.dumps(data, separators=(",", ":")).replace('],[', '],\n[')
with open(sys.argv[2], "w") as f:
    f.write(HEAD + "(function (root) {\n  'use strict';\n  var ns = (root.MyoTwin = root.MyoTwin || {});\n  var data = " + body + ";\n"
            "  (ns.data = ns.data || {}).omniProtons = data;\n  if (typeof module === 'object' && module.exports) module.exports = data;\n"
            "})(typeof globalThis !== 'undefined' ? globalThis : this);\n")
print(len(rows), "hours;", sum(r[1] is None for r in rows), "fill")
