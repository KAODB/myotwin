"""Rebuild data/msl-rad.js: Curiosity RAD dose rate per sol, sols 13-112.

Raw input: the per-observation table extracted from NASA PDS dataset
MSL-M-RAD-3-RDR-V1.0 (https://pds-ppi.igpp.ucla.edu/data/MSL-M-RAD-3-RDR-V1.0/DATA/),
one RAD_RDR_<YYYY>_<DDD>_..._V00.TXT file per sol, fields DOSIMETRY_TOTAL_DOSE_B and _E
(label UNIT "microGray / Hour"). The extract (msl_rad_obs_sol013_112.csv, columns sol, obs,
start_utc, start_mars, qc, duration_s, dose_B_uGy_h, dose_E_uGy_h, source_file) was made by
data-recon/radiation/scripts/msl_rad_extract_obs.py and is not committed.

Usage: python3 -I tools/data/build_msl_rad.py RAW_OBS_CSV data/msl-rad.js

Per sol: median of detector B over every observation of that sol (no screening),
observation count, and the UTC date of the first observation whose time stamp lies within
3 days of the date in the file name (8 observations carry a placeholder stamp).

Written with an SI tool (Claude) and reviewed by the team.
"""
import csv
import datetime as dt
import json
import statistics
import sys
from collections import defaultdict

src, out = sys.argv[1], sys.argv[2]
seen, by = set(), defaultdict(list)
for r in csv.DictReader(open(src)):
    key = (r["source_file"], r["obs"])
    if key not in seen:
        seen.add(key)
        by[int(r["sol"])].append(r)


def utc_date(s):  # "2012-231 22:58:45" -> date
    y, d = s.split()[0].split("-")
    return dt.date(int(y), 1, 1) + dt.timedelta(days=int(d) - 1)


rows = []
for sol in sorted(by):
    rs = by[sol]
    p = rs[0]["source_file"].split("_")
    f0 = dt.date(int(p[2]), 1, 1) + dt.timedelta(days=int(p[3]) - 1)
    good = sorted(utc_date(r["start_utc"]) for r in rs if abs((utc_date(r["start_utc"]) - f0).days) <= 3)
    med = statistics.median(float(r["dose_B_uGy_h"]) for r in rs)
    rows.append([sol, good[0].isoformat(), round(med, 3), len(rs)])

data = {
    "name": "Curiosity RAD dose rate, Mars surface (MSL-M-RAD-3-RDR-V1.0)",
    "source": "NASA Planetary Data System, PPI node: MSL-M-RAD-3-RDR-V1.0 (Curiosity Radiation Assessment Detector, reduced data records), Gale crater surface.",
    "url": "https://pds-ppi.igpp.ucla.edu/data/MSL-M-RAD-3-RDR-V1.0/",
    "retrieved": "2026-11-14",
    "units": "medianB_uGy_h: absorbed dose rate in silicon detector B, microgray per hour (label UNIT \"microGray / Hour\"); date: UTC date of the first observation of the sol.",
    "processing": "For each sol, the median of DOSIMETRY_TOTAL_DOSE_B over all observations in that sol's RDR file (about 44 per sol, 1920 s each), rounded to 0.001 uGy/h. Rebuild: python3 -I tools/data/build_msl_rad.py msl_rad_obs_sol013_112.csv data/msl-rad.js",
    "terms": "PDS data are public; cite Hassler D.M. et al., MSL RAD Reduced Data Records, MSL-M-RAD-3-RDR-V1.0, NASA Planetary Data System.",
    "missingSols": [s for s in range(rows[0][0], rows[-1][0] + 1) if s not in by],
    "columns": ["sol", "date", "medianB_uGy_h", "nObs"],
    "rows": rows,
}
HEAD = """/*
 * Curiosity RAD (Mars surface) absorbed dose rate per sol, sols 13-112.
 * Real measurements from NASA PDS; see data/README.md. Generated by
 * tools/data/build_msl_rad.py; do not edit by hand.
 *
 * Written with an SI tool (Claude) and reviewed by the team.
 */
"""
body = json.dumps(data, separators=(",", ":")).replace('],[', '],\n[')
with open(out, "w") as f:
    f.write(HEAD + "(function (root) {\n  'use strict';\n  var ns = (root.MyoTwin = root.MyoTwin || {});\n  var data = " + body + ";\n"
            "  (ns.data = ns.data || {}).mslRad = data;\n  if (typeof module === 'object' && module.exports) module.exports = data;\n"
            "})(typeof globalThis !== 'undefined' ? globalThis : this);\n")
print(len(rows), "sols; missing", data["missingSols"])
