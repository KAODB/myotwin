"""Rebuild data/lro-crater.js: LRO CRaTER dose per sleep window (22:00-06:00 UTC).

Raw inputs (instrument team, University of New Hampshire, NASA LRO mission; not committed):
  doserates_nospe.txt
    https://crater-web.sr.unh.edu/data/craterProducts/doserates/doserates_nospe.txt
    (hourly 2009-2026; despite the name it includes solar particle events)
  doserates_standard_2017262_31days_allevents.txt
    https://crater-web.sr.unh.edu/data/craterProducts/doserates/data/2017262/doserates_standard_2017262_31days_allevents.txt
    (hourly 2017-08-20 to 2017-09-19; fills 41 hours, 2017-09-02 23:00 to 09-05 23:00, missing from the first file)
Columns used: Julian date (hour centre), D1&2 and D5&6 dose rate in cGy/day (silicon-to-water
corrected, altitude-corrected to the lunar surface by the provider).

Usage: python3 -I tools/data/build_lro_crater.py NOSPE_FILE EVENT_31DAY_FILE data/lro-crater.js

A night starting on date D sums the eight hourly values whose hour starts at D 22:00 ... D+1 05:00;
each hour contributes rate_cGy_day * 1e4 / 24 uGy. Nights with fewer than eight values are
dropped and listed. Where both files have an hour they must agree, or the script stops.

Written with an SI tool (Claude) and reviewed by the team.
"""
import datetime as dt
import json
import sys

nospe, event, out = sys.argv[1:4]
WINDOWS = {"quiet": (dt.date(2017, 4, 21), dt.date(2017, 6, 19)),
           "event": (dt.date(2017, 8, 21), dt.date(2017, 10, 5))}


def hours(fn, years):
    d = {}
    for line in open(fn):
        if line.startswith("#") or not line.strip():
            continue
        p = line.split()
        if p[1] not in years:
            continue
        t = dt.datetime(1970, 1, 1) + dt.timedelta(days=float(p[0]) - 2440587.5)
        d[t.replace(minute=0, second=0, microsecond=0)] = (float(p[7]), float(p[9]))  # D1&2, D5&6
    return d


h = hours(nospe, {"2017"})
for t, v in hours(event, {"2017"}).items():
    if t in h and h[t] != v:
        sys.exit("files disagree at %s: %s vs %s" % (t, h[t], v))
    h[t] = v

data_windows, dropped = {}, []
for name, (d0, d1) in WINDOWS.items():
    rows, day = [], d0
    while day <= d1:
        start = dt.datetime.combine(day, dt.time(22))
        vals = [h.get(start + dt.timedelta(hours=i)) for i in range(8)]
        if None in vals:
            dropped.append(day.isoformat())
        else:
            rows.append([day.isoformat(), round(sum(v[1] for v in vals) * 1e4 / 24, 1),
                         round(sum(v[0] for v in vals) * 1e4 / 24, 1)])
        day += dt.timedelta(days=1)
    data_windows[name] = rows

data = {
    "source": "LRO CRaTER (Cosmic Ray Telescope for the Effects of Radiation) dose-rate products, instrument team, University of New Hampshire, NASA Lunar Reconnaissance Orbiter mission.",
    "url": "https://crater-web.sr.unh.edu/data/craterProducts/doserates/doserates_nospe.txt",
    "urlEventFile": "https://crater-web.sr.unh.edu/data/craterProducts/doserates/data/2017262/doserates_standard_2017262_31days_allevents.txt",
    "retrieved": "2026-11-14",
    "fileHeader": "All dose rate units: cGy / day. All dose rates have a silicon to water correction applied and are altitude corrected to the lunar surface.",
    "units": "D56_uGy, D12_uGy: dose in microgray over the eight hours 22:00-06:00 UTC of the night starting on date (water-corrected, scaled from lunar orbit to the lunar surface by the provider).",
    "processing": "Hourly cGy/day values converted to uGy per hour (x 1e4 / 24) and summed over the eight hours starting 22:00 ... 05:00 UTC; nights with fewer than eight hours dropped. Rebuild: python3 -I tools/data/build_lro_crater.py doserates_nospe.txt doserates_standard_2017262_31days_allevents.txt data/lro-crater.js",
    "terms": "NASA science data are open; cite the CRaTER instrument team (Spence et al. 2010, Space Sci Rev 150:243; Schwadron et al. 2012, JGR 117:E00H13).",
    "droppedNights": dropped,
    "columns": ["date", "D56_uGy", "D12_uGy"],
    "quiet": data_windows["quiet"],
    "event": data_windows["event"],
}
HEAD = """/*
 * LRO CRaTER dose per night (22:00-06:00 UTC), lunar surface equivalent, two
 * windows in 2017. Real measurements; see data/README.md. Generated by
 * tools/data/build_lro_crater.py; do not edit by hand.
 *
 * Written with an SI tool (Claude) and reviewed by the team.
 */
"""
body = json.dumps(data, separators=(",", ":")).replace('],[', '],\n[')
with open(out, "w") as f:
    f.write(HEAD + "(function (root) {\n  'use strict';\n  var ns = (root.MyoTwin = root.MyoTwin || {});\n  var data = " + body + ";\n"
            "  (ns.data = ns.data || {}).lroCrater = data;\n  if (typeof module === 'object' && module.exports) module.exports = data;\n"
            "})(typeof globalThis !== 'undefined' ? globalThis : this);\n")
print({k: len(v) for k, v in data_windows.items()}, "dropped", dropped)
