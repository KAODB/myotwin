"""Rebuild data/donki-sep-2017.js: NASA CCMC DONKI solar energetic particle (SEP) records, September 2017.

Raw input (not committed): the JSON served by
  https://api.nasa.gov/DONKI/SEP?startDate=2017-09-01&endDate=2017-09-30&api_key=DEMO_KEY
(NASA Open APIs gateway to CCMC DONKI). The DONKI flare (FLR) endpoint returned HTTP 404 when the
data were retrieved, so flare ids are only those linked from the SEP records.

Usage: python3 -I tools/data/build_donki_sep.py RAW_SEP_JSON data/donki-sep-2017.js

Selection only: id, start time (UTC), instrument names and linked event ids, unchanged.
"coverage" is the time span the query asked for (startDate 2017-09-01 to endDate 2017-09-30,
whole days); outside it the absence of a record means "not checked", not "no event".

Written with an SI tool (Claude) and reviewed by the team.
"""
import json
import sys

sep = json.load(open(sys.argv[1]))
rows = [[e["sepID"], e["eventTime"], [i["displayName"] for i in e.get("instruments") or []],
         [l["activityID"] for l in e.get("linkedEvents") or []]] for e in sep]
rows.sort(key=lambda r: r[1])
data = {
    "source": "NASA Community Coordinated Modeling Center (CCMC), DONKI (Space Weather Database Of Notifications, Knowledge, Information), SEP records, via the NASA Open APIs gateway.",
    "url": "https://api.nasa.gov/DONKI/SEP?startDate=2017-09-01&endDate=2017-09-30",
    "retrieved": "2026-11-14",
    "units": "start: event time in UTC (ISO 8601, minute precision) as given by DONKI.",
    "processing": "All SEP records returned for 2017-09-01 to 2017-09-30, keeping id, start time, instrument names and linked event ids unchanged, sorted by start time. Rebuild: python3 -I tools/data/build_donki_sep.py api_SEP.json data/donki-sep-2017.js",
    "terms": "DONKI is public; acknowledge \"CCMC DONKI\" (https://ccmc.gsfc.nasa.gov/).",
    "coverage": ["2017-09-01T00:00Z", "2017-10-01T00:00Z"],
    "columns": ["id", "start", "instruments", "linked"],
    "rows": rows,
}
HEAD = """/*
 * NASA CCMC DONKI solar energetic particle records, September 2017. Real
 * records; see data/README.md. Generated by tools/data/build_donki_sep.py;
 * do not edit by hand.
 *
 * Written with an SI tool (Claude) and reviewed by the team.
 */
"""
body = json.dumps(data, separators=(",", ":")).replace('],["2017', '],\n["2017')
with open(sys.argv[2], "w") as f:
    f.write(HEAD + "(function (root) {\n  'use strict';\n  var ns = (root.MyoTwin = root.MyoTwin || {});\n  var data = " + body + ";\n"
            "  (ns.data = ns.data || {}).donkiSep2017 = data;\n  if (typeof module === 'object' && module.exports) module.exports = data;\n"
            "})(typeof globalThis !== 'undefined' ? globalThis : this);\n")
print(len(rows), "SEP records")
