#!/usr/bin/env node
/*
 * Prints docs/EVIDENCE.md from js/evidence.js and the declared assumptions in
 * the model, simulator, phantom, imaging and rules modules. No dependencies.
 *
 *   node tools/evidence-md.js > docs/EVIDENCE.md
 *
 * test/docs.test.js fails when docs/EVIDENCE.md is out of date.
 *
 * Written with an SI tool (Claude) and reviewed by the team.
 */
'use strict';

const path = require('path');
const js = (name) => require(path.join(__dirname, '..', 'js', name));

const TOPIC_TITLES = {
  'challenge resources': 'Resources listed on the challenge page (NASA Human Research Program, Canadian Space Agency)',
  'linked from the challenge resources': 'NASA pages linked from the challenge resources (hazard, risk and research pages)',
  'nasa ratings and requirements': 'NASA Human Research Roadmap ratings, NASA-STD-3001 requirements and technical briefs',
  muscle: 'Muscle',
  mission: 'Mission facts',
  eim: 'Electrical impedance myography (EIM)',
  sleep: 'Sleep',
  radar: 'Radar',
  radiation: 'Radiation environment',
  imaging: 'Cosmic-ray scattering image',
  countermeasure: 'Countermeasures'
};

function cell(v) {
  if (v === null || v === undefined) return '';
  const s = typeof v === 'object' ? JSON.stringify(v) : String(v);
  return s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
}

function table(rows) {
  const out = ['| Name | Value | Unit | Status | Sources | Note |', '|---|---|---|---|---|---|'];
  rows.forEach((r) => {
    out.push('| ' + [r.name, r.value, r.unit, r.status, (r.sources || []).join(', '), r.note].map(cell).join(' | ') + ' |');
  });
  return out;
}

function fromObject(obj, sourceKey) {
  return Object.keys(obj).map((k) => ({
    name: k, value: obj[k].value, unit: obj[k].unit, status: obj[k].status,
    sources: obj[k][sourceKey] || [], note: obj[k].note
  }));
}

function fromArray(arr) {
  return arr.map((a) => ({ name: a.name, value: a.value, unit: a.unit, status: a.status, sources: a.sourceIds || [], note: a.note }));
}

function render() {
  const evidence = js('evidence.js');
  const model = js('model.js');
  const sim = js('sim.js');
  const rules = js('rules.js');
  const phantom = js('phantom.js');
  const imaging = js('imaging.js');

  const L = [];
  L.push('# MyoTwin evidence and assumptions');
  L.push('');
  L.push('Generated by `node tools/evidence-md.js > docs/EVIDENCE.md` from `js/evidence.js` and the');
  L.push('assumption tables in the code. Do not edit by hand; `test/docs.test.js` fails when this file is out of date.');
  L.push('');
  L.push('Status: **verified** means checked against the source text; **secondary** means taken from');
  L.push('another citation without opening the original; **fitted** means estimated from evidence entries;');
  L.push('**assumption** means a modelling choice.');
  L.push('');
  L.push('## Evidence');

  const topics = [];
  evidence.items.forEach((it) => { if (topics.indexOf(it.topic) < 0) topics.push(it.topic); });
  topics.forEach((topic) => {
    L.push('');
    L.push('### ' + (TOPIC_TITLES[topic] || topic));
    evidence.items.filter((it) => it.topic === topic).forEach((it) => {
      L.push('');
      L.push('**' + it.id + '**. ' + it.claim);
      L.push('');
      L.push('- Status: ' + it.status + ' (' + it.level + ')');
      L.push('- Source: ' + it.source + '. <' + it.url + '>');
      L.push('- Quote: ' + (it.quote ? '"' + it.quote + '"' : 'none recorded'));
      const keys = Object.keys(it.values);
      if (keys.length) L.push('- Values: ' + keys.map((k) => '`' + k + '` = ' + cell(it.values[k])).join('; '));
    });
  });

  L.push('');
  L.push('## Assumptions');
  L.push('');
  L.push('### Muscle model parameters (`model.PARAMS`)');
  L.push('');
  L.push(...table(fromObject(model.PARAMS, 'anchors')));
  L.push('');
  L.push('### Simulator assumptions (`sim.ASSUMPTIONS`)');
  L.push('');
  L.push(...table(fromObject(sim.ASSUMPTIONS, 'sourceIds')));
  L.push('');
  L.push('### Simulator noise (`sim.NOISE`)');
  L.push('');
  L.push(...table(fromObject(sim.NOISE, 'sourceIds')));
  L.push('');
  L.push('### Body phantom (`phantom.ASSUMPTIONS`)');
  L.push('');
  L.push(...table(fromArray(phantom.ASSUMPTIONS)));
  L.push('');
  L.push('### Image layers (`imaging.ASSUMPTIONS`)');
  L.push('');
  L.push(...table(fromArray(imaging.ASSUMPTIONS)));
  L.push('');
  L.push('### Status-rule thresholds that are assumptions (`rules.THRESHOLDS`)');
  L.push('');
  const T = rules.THRESHOLDS;
  const thr = {};
  Object.keys(T).filter((k) => T[k].status === 'assumption').forEach((k) => { thr[k] = T[k]; });
  L.push(...table(fromObject(thr, 'sourceIds')));
  L.push('');
  return L.join('\n');
}

if (require.main === module) process.stdout.write(render());

module.exports = { render };
